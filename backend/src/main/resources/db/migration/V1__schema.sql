CREATE TABLE IF NOT EXISTS users (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  username VARCHAR(60) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS wallets (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  owner_id BIGINT NOT NULL,
  account_number VARCHAR(24) NOT NULL UNIQUE,
  balance DECIMAL(18,2) NOT NULL DEFAULT 0,
  CONSTRAINT fk_wallet_owner FOREIGN KEY (owner_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS transfers (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  source_wallet_id BIGINT NOT NULL,
  destination_account VARCHAR(24) NOT NULL,
  destination_name VARCHAR(100) NOT NULL,
  amount DECIMAL(18,2) NOT NULL,
  note VARCHAR(255) NOT NULL DEFAULT '',
  status VARCHAR(20) NOT NULL DEFAULT 'SUCCESS',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_transfer_source FOREIGN KEY (source_wallet_id) REFERENCES wallets(id)
);
CREATE TABLE IF NOT EXISTS security_events (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  event_type VARCHAR(60) NOT NULL,
  severity VARCHAR(20) NOT NULL,
  username VARCHAR(60) NULL,
  details VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS lab_scenarios (
  scenario_key VARCHAR(50) PRIMARY KEY,
  title VARCHAR(150) NOT NULL,
  severity VARCHAR(20) NOT NULL,
  vulnerable_behavior VARCHAR(255) NOT NULL,
  fixed_behavior VARCHAR(255) NOT NULL
);
